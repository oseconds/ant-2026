import { SurfaceField } from '../src/lib/agents/ant/SurfaceField.js';
import { PheromoneField } from '../src/lib/agents/ant/PheromoneField.js';
import { TrailPlateBirth, TRAIL_PLATE_GRID_SIZE, TRAIL_PLATE_SOURCE_ORIGIN,
  TRAIL_PLATE_SOURCE_RADII, TRAIL_PLATE_TARGET_EDGE_DISTANCE } from '../src/lib/agents/ant/TrailPlateBirth.js';
import { pathToFileURL } from 'node:url';

const GRID = TRAIL_PLATE_GRID_SIZE - 1;
const ROUTE_SAMPLES = 240;
const CONTACT_PASSES = 3;
const CONTACT_STRIDE = 2;
const SMOOTHING_SCALES = [0.02, 0.04, 0.08];
const CASES = [
  ['straight', t => 0],
  ['gentle-arc', t => 0.12 * t * t],
  ['tighter-arc', t => 0.20 * t * t],
  ['s-route', t => 0.07 * Math.sin(2 * Math.PI * t)]
];

export function runRouteCurvatureSelectorSurvey() {
  return {
    syntheticConnectedRouteFixtures: CASES.map(([name, offsetX]) => runCase(name, offsetX)),
    defaultDepositQualificationProbe: CASES.flatMap(([name, offsetX]) => [0.5, 0.504]
      .map(baseX => runDefaultDepositProbe(name, offsetX, baseX)))
  };
}

function runCase(name, offsetX) {
  const route = Array.from({ length: ROUTE_SAMPLES + 1 }, (_, index) => {
    const t = index / ROUTE_SAMPLES;
    return { x: 0.504 + offsetX(t), y: 0.64 - 0.6 * t };
  });
  const surface = new SurfaceField();
  const birth = new TrailPlateBirth();
  // Controlled one-cell raster fixture follows the existing TrailPlateBirth field-fixture pattern.
  const chemicalCells = new Set(route.map(({ x, y }) => Math.round(y * GRID) * TRAIL_PLATE_GRID_SIZE
    + Math.round(x * GRID)));
  const chemicalFixture = { width: 96, height: 96, sample(x, y) {
    return chemicalCells.has(Math.round(y * GRID) * TRAIL_PLATE_GRID_SIZE + Math.round(x * GRID)) ? 0.12 : 0;
  } };

  for (let pass = 0; pass < CONTACT_PASSES; pass += 1) {
    const contacts = route.filter((_, index) => index % CONTACT_STRIDE === 0).map((position, index) => ({
      legId: ['FL', 'FR', 'ML', 'MR', 'RL', 'RR'][index % 6], position
    }));
    const event = { type: 'FOOT_CONTACT', contacts };
    surface.applyFootContact(event);
    birth.observeFootContact(event);
  }

  let descriptor = null;
  for (let second = 0; second <= 60 && !descriptor; second += 1) {
    descriptor = birth.advance({ pheromone: chemicalFixture, surface, simulationTimeMs: second * 1000 })[0] || null;
  }
  if (!descriptor) throw new Error(`${name}: production selector did not qualify ${JSON.stringify(birth.getSnapshot().inputDiagnostics)}`);

  const candidate = birth.getSnapshot().candidate;
  const candidatePath = candidate.pathPoints.map(({ x, y }) => ({ x, y }));
  const descriptorPath = descriptor.principalPath.map(index => ({
    x: index % TRAIL_PLATE_GRID_SIZE / GRID,
    y: Math.floor(index / TRAIL_PLATE_GRID_SIZE) / GRID
  }));
  const samePath = candidate.pathPoints.map(point => point.index)
    .every((index, offset) => index === descriptor.principalPath[offset])
    && candidate.pathPoints.length === descriptor.principalPath.length;
  const principal = measurePath(descriptorPath);
  const centerline = measureNetwork(descriptor);
  const sourceAnnulusRadius = Math.hypot(descriptor.source.x - TRAIL_PLATE_SOURCE_ORIGIN.x,
    descriptor.source.y - TRAIL_PLATE_SOURCE_ORIGIN.y);
  const targetEdgeDistance = Math.min(descriptor.target.x, descriptor.target.y,
    1 - descriptor.target.x, 1 - descriptor.target.y);
  return {
    name,
    fixture: {
      routeSamples: route.length,
      field: 'synthetic one-cell raster of an analytic route, not generated by ant trajectory pheromone deposits',
      sourceAnnulusRadii: TRAIL_PLATE_SOURCE_RADII,
      observationBoundaryDistance: TRAIL_PLATE_TARGET_EDGE_DISTANCE,
      acceptedFootContacts: surface.totalFootContacts,
      chemicalSample: 0.12,
      maxSupport: birth.getSnapshot().inputDiagnostics.maxSupport,
      chemicalQualifiedCells: birth.getSnapshot().inputDiagnostics.chemicalQualifiedCells,
      supportedCells: birth.getSnapshot().inputDiagnostics.supportedCells,
      birthAtSeconds: descriptor.bornAtSimulationTimeMs / 1000,
      qualification: 'production TrailPlateBirth.advance over synthetic chemical and real SurfaceField FOOT_CONTACTs; controlled geometry, not natural agent movement'
    },
    source: descriptor.source,
    target: descriptor.target,
    sourceAnnulusRadius,
    targetEdgeDistance,
    candidatePathMatchesDescriptorPrincipalPath: samePath,
    candidatePath: measurePath(candidatePath),
    descriptorPrincipalPath: principal,
    descriptorCenterlineNetwork: centerline,
    productionGeodesicLength: candidate.geodesicLength,
    smoothingScalesWorldUnits: SMOOTHING_SCALES.map(window => ({ window, ...measurePath(descriptorPath, window) }))
  };
}

function measurePath(points, smoothingWindow = 0) {
  const pathLength = length(points);
  const first = points[0], last = points.at(-1);
  const chordLength = Math.hypot(last.x - first.x, last.y - first.y);
  let manhattanLength = 0, diagonals = 0, orthogonals = 0;
  for (let index = 1; index < points.length; index += 1) {
    const dx = Math.abs(points[index].x - points[index - 1].x) * GRID;
    const dy = Math.abs(points[index].y - points[index - 1].y) * GRID;
    manhattanLength += (dx + dy) / GRID;
    if (dx > 0 && dy > 0) diagonals += 1;
    else orthogonals += 1;
  }
  const equalArc = resample(points, Math.min(0.005, Math.max(0.001, pathLength / 200)));
  const compared = smoothingWindow ? smooth(equalArc, smoothingWindow) : equalArc;
  const turns = turnsPerDistance(compared);
  return {
    pointCount: points.length,
    pathLength,
    chordLength,
    tortuosity: chordLength > 1e-9 ? pathLength / chordLength : null,
    manhattanLength,
    manhattanToOctileLength: pathLength ? manhattanLength / pathLength : null,
    diagonalSteps: diagonals,
    orthogonalSteps: orthogonals,
    endpointHeadingRadians: endpointHeadings(points),
    smoothingWindowWorldUnits: smoothingWindow,
    smoothedAbsoluteTurnRadians: turns.absoluteTurn,
    smoothedAbsoluteTurnPerWorldUnit: turns.absoluteTurnPerDistance
  };
}

function measureNetwork(descriptor) {
  const degrees = new Map(descriptor.centerline.map(node => [node.index, 0]));
  let edgeLength = 0;
  for (const [a, b] of descriptor.edges) {
    degrees.set(a, degrees.get(a) + 1);
    degrees.set(b, degrees.get(b) + 1);
    edgeLength += Math.hypot(a % TRAIL_PLATE_GRID_SIZE - b % TRAIL_PLATE_GRID_SIZE,
      Math.floor(a / TRAIL_PLATE_GRID_SIZE) - Math.floor(b / TRAIL_PLATE_GRID_SIZE)) / GRID;
  }
  const counts = { endpoints: 0, junctions: 0, isolated: 0 };
  for (const degree of degrees.values()) {
    if (degree === 1) counts.endpoints += 1;
    else if (degree > 2) counts.junctions += 1;
    else if (degree === 0) counts.isolated += 1;
  }
  return {
    nodeCount: descriptor.centerline.length,
    edgeCount: descriptor.edges.length,
    edgeLength,
    ...counts,
    ribbonCellCount: descriptor.mask.reduce((sum, value) => sum + value, 0)
  };
}

function runDefaultDepositProbe(name, offsetX, baseX) {
  const route = Array.from({ length: ROUTE_SAMPLES + 1 }, (_, index) => {
    const t = index / ROUTE_SAMPLES;
    return { x: baseX + offsetX(t), y: 0.64 - 0.6 * t };
  });
  const pheromone = new PheromoneField();
  const surface = new SurfaceField();
  const birth = new TrailPlateBirth();
  for (let pass = 0; pass < 6; pass += 1) {
    for (let index = 1; index < route.length; index += 1) pheromone.depositSegment(route[index - 1], route[index]);
    const event = { type: 'FOOT_CONTACT', contacts: route.filter((_, index) => index % 3 === 0)
      .map((position, index) => ({ legId: ['FL', 'FR', 'ML', 'MR', 'RL', 'RR'][index % 6], position })) };
    surface.applyFootContact(event);
    birth.observeFootContact(event);
  }
  let descriptor = null;
  for (let second = 0; second <= 60 && !descriptor; second += 1) {
    descriptor = birth.advance({ pheromone, surface, simulationTimeMs: second * 1000 })[0] || null;
  }
  return {
    name,
    baseX,
    pheromoneRadiusWorldUnits: 0.0045,
    fieldQualification: 'real PheromoneField.depositSegment and SurfaceField.applyFootContact; no selector changes',
    acceptedFootContacts: surface.totalFootContacts,
    chemicalQualifiedCells: birth.getSnapshot().inputDiagnostics.chemicalQualifiedCells,
    supportedCells: birth.getSnapshot().inputDiagnostics.supportedCells,
    selectedCandidate: Boolean(birth.getSnapshot().candidate),
    birth: Boolean(descriptor),
    productionGeodesicLength: descriptor?.metrics.geodesicLength ?? null
  };
}

function length(points) {
  let total = 0;
  for (let index = 1; index < points.length; index += 1) {
    total += Math.hypot(points[index].x - points[index - 1].x, points[index].y - points[index - 1].y);
  }
  return total;
}

function resample(points, step) {
  const distances = [0];
  for (let index = 1; index < points.length; index += 1) {
    distances.push(distances.at(-1) + Math.hypot(points[index].x - points[index - 1].x, points[index].y - points[index - 1].y));
  }
  const output = [];
  let segment = 1;
  for (let distance = 0; distance < distances.at(-1); distance += step) {
    while (segment < distances.length - 1 && distances[segment] < distance) segment += 1;
    const fraction = (distance - distances[segment - 1]) / (distances[segment] - distances[segment - 1]);
    output.push(interpolate(points[segment - 1], points[segment], fraction));
  }
  output.push(points.at(-1));
  return output;
}

function smooth(points, window) {
  const distances = [0];
  for (let index = 1; index < points.length; index += 1) distances.push(distances.at(-1) + Math.hypot(
    points[index].x - points[index - 1].x, points[index].y - points[index - 1].y));
  const radius = window / 2;
  return points.map((point, index) => {
    if (index === 0 || index === points.length - 1) return point;
    let x = 0, y = 0, weight = 0;
    for (let sample = 0; sample < points.length; sample += 1) {
      if (Math.abs(distances[sample] - distances[index]) > radius) continue;
      x += points[sample].x; y += points[sample].y; weight += 1;
    }
    return { x: x / weight, y: y / weight };
  });
}

function turnsPerDistance(points) {
  let absoluteTurn = 0, distance = 0, previous = null;
  for (let index = 1; index < points.length; index += 1) {
    const dx = points[index].x - points[index - 1].x, dy = points[index].y - points[index - 1].y;
    const segmentLength = Math.hypot(dx, dy);
    if (!segmentLength) continue;
    const heading = Math.atan2(dy, dx);
    if (previous !== null) absoluteTurn += Math.abs(wrapAngle(heading - previous));
    previous = heading; distance += segmentLength;
  }
  return { absoluteTurn, absoluteTurnPerDistance: distance ? absoluteTurn / distance : null };
}

function endpointHeadings(points) {
  let first = 1, last = points.length - 1;
  while (first < points.length && distance(points[0], points[first]) < 1e-12) first += 1;
  while (last > 0 && distance(points[last - 1], points.at(-1)) < 1e-12) last -= 1;
  return {
    sourceRadians: Math.atan2(points[first].y - points[0].y, points[first].x - points[0].x),
    targetRadians: Math.atan2(points.at(-1).y - points[last - 1].y, points.at(-1).x - points[last - 1].x)
  };
}

function interpolate(a, b, amount) { return { x: a.x + (b.x - a.x) * amount, y: a.y + (b.y - a.y) * amount }; }
function distance(a, b) { return Math.hypot(a.x - b.x, a.y - b.y); }
function wrapAngle(angle) { return Math.atan2(Math.sin(angle), Math.cos(angle)); }

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  process.stdout.write(JSON.stringify(runRouteCurvatureSelectorSurvey(), null, 2) + '\n');
}
